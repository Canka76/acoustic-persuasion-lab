"""Print 79%-correct threshold per layer and write operating_point.json. Stub — Step 4."""
from __future__ import annotations

import json
import sys
from pathlib import Path

_PILOT_JSON = Path(__file__).parent / "threshold_pilot.json"
_OP_JSON = Path(__file__).parent.parent / "corpus" / "scripts" / "operating_point.json"
_FLOOR_SNR_DB = -40.0
_MARGIN_DB = 6.0


def main() -> None:
    if not _PILOT_JSON.exists():
        print(f"ERROR: {_PILOT_JSON} not found — run threshold pilot first.", file=sys.stderr)
        sys.exit(1)

    pilot = json.loads(_PILOT_JSON.read_text())
    results: dict[str, float] = {}
    for layer in ("subharmonic", "am"):
        threshold_db = float(pilot[layer]["threshold_snr_db"])
        operating_db = max(threshold_db - _MARGIN_DB, _FLOOR_SNR_DB)
        results[layer] = operating_db
        print(f"{layer}: 79%-threshold = {threshold_db:.1f} dB SNR → operating point = {operating_db:.1f} dB SNR")
        if threshold_db <= _FLOOR_SNR_DB:
            print(
                f"  WARNING: threshold ≤ floor ({_FLOOR_SNR_DB} dB). "
                "'Sub-perceptual' framing may be falsified at this dose. "
                "Proceeding at floor; H3 should be reported as 'not achievable at effective dose'."
            )

    op = {
        "target_snr_db": min(results.values()),
        "per_layer": results,
        "note": "Generated by threshold_report.py from n=12 pilot data.",
    }
    _OP_JSON.write_text(json.dumps(op, indent=2))
    print(f"\nWrote operating point → {_OP_JSON}")


if __name__ == "__main__":
    main()
