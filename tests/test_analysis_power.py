"""Pre-registered power validation test.

Loads analysis/simulation_results.json (generated by analysis/simulate.py).
If the file is absent, runs the simulation inline before asserting.

Pre-registered assertions (§8 of preregistration.md):
  - power (B-A planned contrast, p < .05) >= 0.80
  - type-I error (null condition, B-A planned contrast, p < .05) in [0.03, 0.07]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

# Ensure repo root is importable when running from any cwd
_repo_root = Path(__file__).resolve().parent.parent
if str(_repo_root) not in sys.path:
    sys.path.insert(0, str(_repo_root))

_SIM_RESULTS = _repo_root / "analysis" / "simulation_results.json"


def _load_or_run() -> dict:
    """Return simulation results, running simulate.run() if the JSON is absent."""
    if _SIM_RESULTS.exists():
        with open(_SIM_RESULTS) as f:
            return json.load(f)

    print(
        f"\n[test_analysis_power] {_SIM_RESULTS.name} not found — running simulate.run() inline.",
        flush=True,
    )
    # simulate.py uses a relative import from analyze; set up path so both resolve
    _analysis_dir = str(_repo_root / "analysis")
    if _analysis_dir not in sys.path:
        sys.path.insert(0, _analysis_dir)

    import importlib
    simulate = importlib.import_module("simulate")
    return simulate.run()


@pytest.fixture(scope="module")
def sim_results() -> dict:
    return _load_or_run()


def test_power_geq_080(sim_results: dict) -> None:
    """Power on the B-A planned contrast must be >= 0.80 at Δd′ = 0.45."""
    # simulate.run() returns {"power": {"anova": ..., "contrast_BA": ...}, ...}
    power_block = sim_results.get("power", {})
    # Support both flat (float) and nested (dict) formats for resilience
    if isinstance(power_block, dict):
        power = power_block.get("contrast_BA", power_block.get("contrast_b_a"))
    else:
        power = float(power_block)

    assert power is not None, "power key missing from simulation_results.json"
    assert power >= 0.80, (
        f"Power {power:.3f} < 0.80. "
        f"Parameters: n_per_arm={sim_results.get('parameters', {}).get('n_per_arm')}, "
        f"delta_d={sim_results.get('parameters', {}).get('effect_delta_dprime')}."
    )


def test_type_i_in_range(sim_results: dict) -> None:
    """Type-I error on the B-A planned contrast must be in [0.03, 0.07] (null condition)."""
    type1_block = sim_results.get("type1_error", sim_results.get("type_i"))
    if isinstance(type1_block, dict):
        type_i = type1_block.get("contrast_BA", type1_block.get("contrast_b_a"))
    else:
        type_i = float(type1_block) if type1_block is not None else None

    assert type_i is not None, "type1_error key missing from simulation_results.json"
    assert 0.03 <= type_i <= 0.07, (
        f"Type-I error {type_i:.3f} outside [0.03, 0.07]. Expected ≈ 0.05 ± 0.02."
    )
